import { test } from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import os from 'node:os';
import crypto from 'node:crypto';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHandoverServer } from '../src/server.mjs';

const exec = promisify(execFile);
test('用户名客户端：无全局或每请求 token，全程恢复与配置切换保留归属', async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'handover-username-cli-'));
  const app = createHandoverServer({ dataDir: path.join(dir, 'data'), agentToken: undefined, adminToken: 'isolated-admin-fixture-'.repeat(3), port: 0, publicUrl: 'http://127.0.0.1:0', disablePush: true });
  await new Promise(resolve => app.server.listen(0, '127.0.0.1', resolve));
  t.after(async () => { app.server.closeAllConnections(); await new Promise(resolve => app.server.close(resolve)); fs.rmSync(dir, { recursive: true, force: true }); });
  const url = `http://127.0.0.1:${app.server.address().port}`;
  const env = { ...process.env, CODEX_THREAD_ID: 'username-cli-source', HANDOVER_SERVER_URL: url, HANDOVER_CONFIG: path.join(dir, 'config.json'), HANDOVER_STATE_DIR: path.join(dir, 'handles'), HANDOVER_NO_OPEN: '1', HANDOVER_SKIP_UPDATE: '1' };
  delete env.HANDOVER_AGENT_TOKEN; delete env.HANDOVER_USERNAME;
  const cli = path.resolve('skills/grill-with-ui/scripts/handover.mjs');
  const run = async (args, extra = {}) => { try { const r = await exec(process.execPath, [cli, ...args], { env: { ...env, ...extra } }); return { code: 0, data: JSON.parse(r.stdout) }; } catch (e) { return { code: e.code, data: JSON.parse(e.stdout) }; } };
  assert.equal((await run(['config', '--show'])).data.username, 'Xpy');
  assert.equal((await run(['probe'])).data.available, true);
  assert.equal((await run(['home'])).data.url, url + '/?username=Xpy');
  const created = await run(['new', '--kind', 'help', '--topic', '隔离的用户名测试']);
  assert.equal(created.code, 0, JSON.stringify(created.data));
  assert.match(created.data.url, /username=Xpy/);
  const handle = created.data.handle, h = JSON.parse(fs.readFileSync(handle, 'utf8'));
  assert.equal(h.schema, 2); assert.equal(h.username, 'Xpy'); assert.equal(h.requestToken, undefined); assert.equal(h.creation.requestToken, undefined);
  assert.equal(Object.keys(app.store.all('tickets')).length, 0);
  assert.equal(Object.keys(app.store.all('sessions')).length, 0);
  assert.equal((await run(['wait', '--handle', handle, '--timeout', '0'])).code, 3);
  assert.equal((await run(['state', '--handle', handle], { CODEX_THREAD_ID: 'wrong-source' })).code, 1);
  await run(['config', '--username', 'OtherUser']);
  assert.equal((await run(['state', '--handle', handle])).data.username, 'Xpy');
  assert.match((await run(['open', '--handle', handle])).data.url, /username=Xpy/);
  const sent = await fetch(url + `/grill/${h.id}/send?username=Xpy`, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ submissionId: crypto.randomUUID(), actions: [{ q: 'q1', type: 'answer', kind: 'text', text: '合成反馈' }] }) });
  assert.equal(sent.status, 200);
  const waiting = await run(['wait', '--handle', handle, '--timeout', '0'], { HANDOVER_USERNAME: 'OtherUser' });
  assert.equal(waiting.code, 0); assert.equal(waiting.data.username, 'Xpy'); assert.equal(waiting.data.events[0].seq, 1);
  const patchFile = path.join(dir, 'patch.json'); fs.writeFileSync(patchFile, JSON.stringify({ questions: [{ id: 'q1', answer: { kind: 'text', text: '合成反馈' }, status: 'answered' }] }));
  assert.equal((await run(['patch', '--handle', handle, '--file', patchFile])).code, 0);
  assert.equal((await run(['ack', '--handle', handle, '--seq', '1'])).data.handled, 1);
  assert.equal((await run(['resume', '--handle', handle])).data.handled, 1);
  assert.equal((await run(['pending', '--handle', handle])).data.events.length, 0);
  assert.equal((await run(['finish', '--handle', handle])).code, 0);
  assert.equal((await run(['resume', '--handle', handle])).data.status, 'completed');
  assert.equal(app.store.list().length, 1);
  assert.equal(JSON.parse(fs.readFileSync(handle, 'utf8')).username, 'Xpy');
});

test('创建和恢复请求不打开网页；仅显式 open 才调用浏览器', async (t) => {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'handover-no-auto-open-'));
  const app = createHandoverServer({dataDir:path.join(dir,'data'),adminToken:'isolated-no-open-fixture-'.repeat(3),port:0,publicUrl:'http://127.0.0.1:0',disablePush:true});
  await new Promise(resolve => app.server.listen(0,'127.0.0.1',resolve));
  t.after(async()=>{app.server.closeAllConnections();await new Promise(resolve=>app.server.close(resolve));fs.rmSync(dir,{recursive:true,force:true});});
  const marker=path.join(dir,'browser-calls.jsonl'),preload=path.join(dir,'opener.mjs');
  fs.writeFileSync(preload, `import child from 'node:child_process'; import fs from 'node:fs'; import {syncBuiltinESMExports} from 'node:module'; const original=child.execFileSync; child.execFileSync=(program,args,options)=>{if(['/usr/bin/open','rundll32.exe','xdg-open'].includes(program)){fs.appendFileSync(process.env.BROWSER_CALLS,JSON.stringify({program,args})+'\\n');return '';}return original(program,args,options);};syncBuiltinESMExports();`);
  const env={...process.env,HANDOVER_SERVER_URL:`http://127.0.0.1:${app.server.address().port}`,HANDOVER_USERNAME:'Xpy',HANDOVER_CONFIG:path.join(dir,'config.json'),HANDOVER_STATE_DIR:path.join(dir,'handles'),CODEX_THREAD_ID:'no-open-fixture',HANDOVER_SKIP_UPDATE:'1',NODE_OPTIONS:`--import=${preload}`,BROWSER_CALLS:marker};
  delete env.HANDOVER_NO_OPEN;
  const run=async args=>JSON.parse((await exec(process.execPath,[path.resolve('cli.mjs'),...args],{env})).stdout);
  const created=await run(['new','--kind','help','--topic','隔离验证：不自动弹出网页']);
  assert.equal(created.opened,false);assert.equal(fs.existsSync(marker),false);
  assert.equal((await run(['resume','--handle',created.handle])).requestId,created.requestId);
  assert.equal(fs.existsSync(marker),false);
  const opened=await run(['open','--handle',created.handle]);assert.equal(opened.opened,true);
  const calls=fs.readFileSync(marker,'utf8').trim().split('\n').map(JSON.parse);
  assert.equal(calls.length,1);assert.deepEqual(calls[0].args,[created.url]);
});
